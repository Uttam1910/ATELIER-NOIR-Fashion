export const productBySlug = new Map(products.map((p) => [p.slug, p]))

export const getProduct = (slug: string | undefined) =>
  slug ? productBySlug.get(slug) : undefined

export const getProducts = (slugs: string[]) =>
  slugs.map((s) => productBySlug.get(s)).filter((p): p is Product => Boolean(p))

export const newArrivals = products
  .filter((p) => p.newArrival)
  .sort((a, b) => b.addedAt.localeCompare(a.addedAt))
