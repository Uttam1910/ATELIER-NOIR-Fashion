/* ---------- Shared option presets (kept here so each product stays readable) ---------- */

const APPAREL_SIZES = ['XS', 'S', 'M', 'L', 'XL', 'XXL']
const BLOUSE_SIZES = ['32', '34', '36', '38', '40', '42']

